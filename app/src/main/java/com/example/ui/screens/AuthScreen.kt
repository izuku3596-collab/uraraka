            Text(
                text = "Conéctate con Ochako Uraraka y guarda tu nivel de héroe, sesiones de entrenamiento y comandos de voz en la nube.",
                color = Color.LightGray,
                fontSize = 13.sp,
                textAlign = TextAlign.Center,
                lineHeight = 19.sp,
                modifier = Modifier.padding(top = 8.dp, bottom = 22.dp)
            )

            Card(
